/// The Lean toolchain used by generated packages and runtimes.
pub const LEAN_TOOLCHAIN: &str = "leanprover/lean4:v4.35.0";

/// Main configuration object for code-generation in Lean 4.
pub struct CodeGenerator<'a> {
    /// Language-independent configuration.
    config: &'a CodeGeneratorConfig,
    /// Mapping from external type names to fully-qualified names.
    external_qualified_names: HashMap<String, String>,
}

/// Shared state for the code generation of a Lean source file.
struct LeanEmitter<'a, T> {
    /// Writer.
    out: IndentedWriter<T>,
    /// Generator.
    generator: &'a CodeGenerator<'a>,
    /// Current namespace (e.g. vec!["my_module", "MyStruct"]), used to look up comments.
    current_namespace: Vec<String>,
    /// Containers of the recursive group currently being defined, if any.
    recursive_names: Vec<String>,
    /// Containers whose (de)serializers come with proofs, i.e. those that do not depend on
    /// external definitions (see also `Analysis::floats`).
    proven: BTreeSet<String>,
    /// Containers whose serializers come with proofs of injectivity, i.e. those that are
    /// proven and do not contain maps.
    injective: BTreeSet<String>,
    /// For each container, a value of the type (as a Lean term) and the rank at which it was
    /// found, so that `Inhabited` instances only use instances defined before them.
    witnesses: BTreeMap<String, (usize, String)>,
    /// Analysis of the containers, for maps and proofs.
    analysis: Analysis,
}

/// Properties of containers used to represent maps and to generate proofs.
#[derive(Clone, Default)]
struct Analysis {
    /// Containers that can be keys of hash maps: they are not recursive, and do not contain
    /// floats, maps, or external types.
    hashable: BTreeSet<String>,
    /// Hashable containers used in keys of maps, which derive `Hashable` and `LawfulBEq`.
    key_types: BTreeSet<String>,
    /// Proven containers that contain maps, whose (de)serializers round-trip up to an
    /// equivalence relation.
    equiv: BTreeSet<String>,
    /// Containers that contain floats, for which Bincode has no proofs.
    floats: BTreeSet<String>,
}

